-- Idempotent baseline for the schema the API used to create on boot.
-- Safe on a database that already has these tables. Columns that were created
-- as integer are widened to bigint only while they are still integer.
-- The runner records this file in schema_migrations and holds the advisory lock.

create table if not exists users (
  id integer generated by default as identity primary key,
  google_sub text unique not null,
  email text not null,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists grants (
  user_id integer not null references users (id),
  exam text not null,
  granted_by integer references users (id),
  created_at timestamptz not null default now(),
  primary key (user_id, exam)
);

create table if not exists access_requests (
  id integer generated by default as identity primary key,
  user_id integer not null references users (id),
  exam text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  unique (user_id, exam)
);

alter table access_requests add column if not exists plan text;

create table if not exists attempts (
  id integer generated by default as identity primary key,
  user_id integer not null references users (id),
  exam text not null,
  score integer not null,
  total integer not null,
  created_at timestamptz not null default now()
);

create table if not exists sessions (
  sid text primary key,
  data text not null,
  expires bigint not null
);

create table if not exists audit (
  id integer generated by default as identity primary key,
  actor_id integer references users (id),
  user_id integer references users (id),
  exam text not null,
  action text not null,
  created_at timestamptz not null default now()
);

alter table audit add column if not exists detail text;

create table if not exists runs (
  id text primary key,
  user_id integer references users (id),
  exam text not null,
  test_number text not null,
  started_at bigint not null,
  deadline bigint not null,
  answers text not null default '{}',
  result text,
  finished_at bigint
);

create index if not exists runs_lookup on runs (user_id, exam, test_number);
create index if not exists sessions_expires on sessions (expires);

create table if not exists orders (
  id integer primary key,
  code text unique not null,
  user_id integer not null,
  plan text not null,
  group_size integer not null,
  friend_emails text not null default '[]',
  amount_mnt integer not null,
  list_amount_mnt integer not null,
  sale_applied integer not null default 0,
  status text not null default 'awaiting_payment',
  expires_at bigint not null,
  paid_at bigint,
  note text,
  created_at bigint not null
);

create table if not exists entitlements (
  id integer primary key,
  user_id integer,
  email text not null,
  starts_at bigint not null,
  ends_at bigint not null,
  source text not null,
  order_id integer,
  created_by integer,
  created_at bigint not null
);

create index if not exists entitlements_user on entitlements (user_id, ends_at);
create index if not exists entitlements_email on entitlements (email);
-- These three indexes are built inside the migration transaction, which blocks
-- writes on each table for the build. orders, entitlements, and account_notices
-- hold one row per purchase, grant, or notice for a single academy, so the lock
-- is expected to be brief. CREATE INDEX CONCURRENTLY cannot run in this
-- transaction. Use it in a later file only if one of these tables grows large.
create index if not exists entitlements_email_lower on entitlements (lower(email));
create index if not exists orders_user on orders (user_id, created_at);

create table if not exists sms_payment_events (
  id text primary key,
  sms_hash text not null unique,
  account_masked text,
  amount_mnt integer,
  utga text,
  order_code text,
  phone_received_at text,
  server_received_at bigint not null,
  status text not null,
  unmatched_reason text,
  review_note text,
  order_id integer,
  created_at bigint not null
);
create index if not exists sms_events_status on sms_payment_events (status, created_at);
create index if not exists sms_events_code on sms_payment_events (order_code);

create table if not exists sms_rate_hits (
  id text primary key,
  ip text not null,
  created_at bigint not null
);
create index if not exists sms_rate_hits_ip on sms_rate_hits (ip, created_at);

create table if not exists user_sessions (
  sid_hash text primary key,
  sid text not null unique,
  user_id integer not null,
  created_at bigint not null,
  last_seen bigint not null,
  label text not null,
  network text not null
);
create index if not exists user_sessions_user on user_sessions (user_id, created_at, sid_hash);

create table if not exists account_notices (
  id text primary key,
  user_id integer,
  email text,
  kind text not null,
  separate integer not null default 0,
  created_at bigint not null
);
create index if not exists account_notices_user on account_notices (user_id, created_at);
create index if not exists account_notices_email_lower on account_notices (lower(email), created_at);

do $$
declare
  item text[];
  kind text;
  plan text[][] := array[
    array['entitlements', 'starts_at'],
    array['entitlements', 'ends_at'],
    array['entitlements', 'created_at'],
    array['orders', 'created_at'],
    array['orders', 'expires_at'],
    array['orders', 'paid_at']
  ];
begin
  foreach item slice 1 in array plan loop
    select data_type into kind
    from information_schema.columns
    where table_schema = 'public'
      and table_name = item[1]
      and column_name = item[2];
    if kind = 'integer' then
      execute format('alter table public.%I alter column %I type bigint', item[1], item[2]);
    elsif kind is distinct from 'bigint' then
      raise exception 'millis migration incomplete: public.%.%', item[1], item[2];
    end if;
  end loop;
end $$;

create sequence if not exists orders_id_seq;
alter table orders alter column id set default nextval('orders_id_seq');
alter sequence orders_id_seq owned by orders.id;
select setval('orders_id_seq', greatest(coalesce((select max(id) from orders), 0), 1));

create sequence if not exists entitlements_id_seq;
alter table entitlements alter column id set default nextval('entitlements_id_seq');
alter sequence entitlements_id_seq owned by entitlements.id;
select setval('entitlements_id_seq', greatest(coalesce((select max(id) from entitlements), 0), 1));

