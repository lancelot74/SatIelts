do $$
declare
  role_name text;
begin
  foreach role_name in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = role_name) then
      execute format(
        'revoke all on table users, grants, access_requests, attempts, sessions, audit, runs, orders, entitlements, sms_payment_events, sms_rate_hits, user_sessions, account_notices, schema_migrations from %I',
        role_name
      );
      execute format(
        'revoke all on sequence orders_id_seq, entitlements_id_seq from %I',
        role_name
      );
    end if;
  end loop;
end $$;

-- Expired rows that were never tied to a signed-in account.
delete from sessions
where expires <= (extract(epoch from now()) * 1000)::bigint
  and not exists (
    select 1 from user_sessions where user_sessions.sid = sessions.sid
  );
